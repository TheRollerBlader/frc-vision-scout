    def _chart_10_ml_role_clustering(self, df_robots: pd.DataFrame) -> Dict[str, Any]:
        """Unsupervised ML Clustering of Robot Playstyles following `ml-best-practices`."""
        feature_cols = [
            "estimated_distance_feet",
            "mean_speed_fps",
            "max_speed_fps",
            "stationary_seconds",
            "time_in_own_zone_pct",
            "time_in_neutral_zone_pct",
            "time_in_enemy_zone_pct",
            "estimated_cycles",
            "defense_engagement_sec",
            "fuel_proximity_frames",
        ]
        available_cols = [c for c in feature_cols if c in df_robots.columns]
        if len(df_robots) < 6 or len(available_cols) < 4:
            return {}

        # Handle missing/NULL values explicitly per ML best practices
        X_raw = df_robots[available_cols].fillna(0.0).values
        scaler = StandardScaler()
        X_scaled = scaler.fit_transform(X_raw)

        # Evaluate Silhouette Score across k = 2..min(6, len-1)
        k_range = list(range(2, min(7, len(df_robots))))
        sil_scores: List[float] = []
        best_k = 3
        best_sil = -1.0

        for k in k_range:
            km = KMeans(n_clusters=k, random_state=42, n_init=10)
            lbls = km.fit_predict(X_scaled)
            score = float(silhouette_score(X_scaled, lbls))
            sil_scores.append(score)
            if score > best_sil:
                best_sil = score
                best_k = k

        km_opt = KMeans(n_clusters=best_k, random_state=42, n_init=10)
        cluster_labels = km_opt.fit_predict(X_scaled)
        df_robots["ml_cluster_id"] = cluster_labels

        pca = PCA(n_components=2, random_state=42)
        X_pca = pca.fit_transform(X_scaled)
        df_robots["pca_1"] = X_pca[:, 0]
        df_robots["pca_2"] = X_pca[:, 1]

        # Save updated robot dataframe with ML cluster assignments
        for target_dir in [self.repo_data_dir, self.ssd_data_dir]:
            df_robots.to_csv(target_dir / "per_robot_match_telemetry.csv", index=False)

        fig, axes = plt.subplots(1, 3, figsize=(18, 5.5))

        # Panel 1: Silhouette Score vs k
        axes[0].plot(k_range, sil_scores, marker="o", lw=2.5, color="#38bdf8")
        axes[0].axvline(best_k, color="#f59e0b", ls="--", lw=2, label=f"Optimal k={best_k} (Silhouette={best_sil:.3f})")
        axes[0].set_title("K-Means Silhouette Score Optimization")
        axes[0].set_xlabel("Number of Clusters (k)")
        axes[0].set_ylabel("Silhouette Score")
        axes[0].legend(frameon=True, facecolor="#0f172a")
        axes[0].grid(True)

        # Panel 2: 2D PCA Scatter colored by K-Means Cluster ID
        palette = ["#10b981", "#3b82f6", "#f59e0b", "#ef4444", "#a855f7", "#ec4899"]
        for cid in sorted(set(cluster_labels)):
            mask = cluster_labels == cid
            axes[1].scatter(
                X_pca[mask, 0],
                X_pca[mask, 1],
                label=f"Cluster {cid} (n={int(np.sum(mask))})",
                color=palette[cid % len(palette)],
                s=65,
                alpha=0.88,
                edgecolors="white",
            )
        for _, row in df_robots.head(18).iterrows():
            axes[1].annotate(
                row["team_key"].replace("frc", ""),
                (row["pca_1"], row["pca_2"]),
                fontsize=7.5,
                xytext=(3, 3),
                textcoords="offset points",
                color="#e2e8f0",
            )
        axes[1].set_title(f"2D PCA Projection Colored by K-Means Cluster (k={best_k})")
        axes[1].set_xlabel(f"PCA Component 1 ({pca.explained_variance_ratio_[0]*100:.1f}% var)")
        axes[1].set_ylabel(f"PCA Component 2 ({pca.explained_variance_ratio_[1]*100:.1f}% var)")
        axes[1].legend(frameon=True, facecolor="#0f172a")
        axes[1].grid(True)

        # Panel 3: 2D PCA Scatter colored by Tactical Role (Discrete Feature Hue)
        roles = df_robots["classified_role"].unique()
        for r_idx, role_name in enumerate(roles):
            mask = df_robots["classified_role"] == role_name
            axes[2].scatter(
                df_robots.loc[mask, "pca_1"],
                df_robots.loc[mask, "pca_2"],
                label=role_name,
                color=palette[r_idx % len(palette)],
                marker="s",
                s=65,
                alpha=0.88,
                edgecolors="white",
            )
        axes[2].set_title("2D PCA Projection Colored by Tactical Role Classification")
        axes[2].set_xlabel("PCA Component 1")
        axes[2].set_ylabel("PCA Component 2")
        axes[2].legend(frameon=True, facecolor="#0f172a")
        axes[2].grid(True)

        fig.suptitle("Unsupervised ML Robot Playstyle Clustering (PCA + Silhouette Optimization)", fontsize=14, fontweight="bold", y=1.03)
        self._save_fig(fig, "10_robot_role_clustering_pca_silhouette.png")

        return {
            "optimal_kmeans_k": int(best_k),
            "optimal_silhouette_score": round(best_sil, 4),
            "pca_var_explained_pct": round(float(np.sum(pca.explained_variance_ratio_) * 100), 1),
        }

