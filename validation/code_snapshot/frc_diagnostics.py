def bootstrap_ci(values: np.ndarray, n_boot: int = 500, seed: int = 42) -> Tuple[float, float, float]:
    """Calculates mean and 95% bootstrap confidence interval."""
    clean = np.asarray(values, dtype=np.float64)
    clean = clean[~np.isnan(clean)]
    if len(clean) == 0:
        return 0.0, 0.0, 0.0
    if len(clean) == 1:
        v = float(clean[0])
        return v, v, v
    rng = np.random.default_rng(seed)
    means = [float(np.mean(rng.choice(clean, size=len(clean), replace=True))) for _ in range(n_boot)]
    return float(np.mean(clean)), float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


class FRCDiagnosticsSuite:
    """Generates all charts, robot scouting profiles, TBA correlations, and GitHub reports."""

    def __init__(
        self,
        ssd_analytics_dir: Path,
        repo_output_dir: Path,
        tba_cache_dir: Path = Path(".cache/tba"),
        training_csv_path: Path = Path("models/training_artifacts/runs/frc/results.csv"),
    ):
        self.ssd_analytics_dir = ssd_analytics_dir
        self.repo_output_dir = repo_output_dir
        self.tba_cache_dir = tba_cache_dir
        self.training_csv_path = training_csv_path

        self.repo_charts_dir = self.repo_output_dir / "charts"
        self.ssd_charts_dir = self.ssd_analytics_dir / "charts"
        self.repo_profiles_dir = self.repo_output_dir / "robot_profiles"
        self.ssd_profiles_dir = self.ssd_analytics_dir / "robot_profiles"
        self.repo_data_dir = self.repo_output_dir / "data"
        self.ssd_data_dir = self.ssd_analytics_dir / "data"

        for d in [
            self.repo_charts_dir,
            self.ssd_charts_dir,
            self.repo_profiles_dir,
            self.ssd_profiles_dir,
            self.repo_data_dir,
            self.ssd_data_dir,
        ]:
            d.mkdir(parents=True, exist_ok=True)

    def _save_fig(self, fig: plt.Figure, filename: str) -> None:
        """Saves a figure to both the GitHub repo charts directory and Extreme SSD."""
        repo_path = self.repo_charts_dir / filename
        ssd_path = self.ssd_charts_dir / filename
        fig.savefig(str(repo_path), dpi=180, bbox_inches="tight", facecolor=fig.get_facecolor())
        fig.savefig(str(ssd_path), dpi=180, bbox_inches="tight", facecolor=fig.get_facecolor())
        plt.close(fig)
        print(f"[Diagnostics] Saved chart: {filename}")

    def load_datasets(self) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
        """Loads frame evaluations, box detections, per-robot telemetry, and trajectories."""
        frames_csv = self.repo_data_dir / "frame_evaluation_results.csv"
        boxes_csv = self.repo_data_dir / "all_bounding_box_detections.csv"
        robots_csv = self.repo_data_dir / "per_robot_match_telemetry.csv"
        traj_csv = self.repo_data_dir / "all_robot_trajectories.csv"

        df_frames = pd.read_csv(frames_csv) if frames_csv.is_file() else pd.DataFrame()
        df_boxes = pd.read_csv(boxes_csv) if boxes_csv.is_file() else pd.DataFrame()
        df_robots = pd.read_csv(robots_csv) if robots_csv.is_file() else pd.DataFrame()
        df_traj = pd.read_csv(traj_csv) if traj_csv.is_file() else pd.DataFrame()

        return df_frames, df_boxes, df_robots, df_traj

    def enrich_with_tba_match_data(self, df_frames: pd.DataFrame) -> pd.DataFrame:
        """Joins frame-level vision metrics with official TBA match scores & 2026 hubScore breakdowns."""
        if df_frames.empty:
            return pd.DataFrame()

        match_rows: List[Dict[str, Any]] = []
        for (event_key, match_key, year, split), grp in df_frames.groupby(["event_key", "match_key", "year", "split"]):
            cache_file = self.tba_cache_dir / f"event_{event_key}_matches.json"
            tba_match = None
            if cache_file.is_file():
                try:
                    with open(cache_file, "r", encoding="utf-8") as f:
                        matches = json.load(f)
                    if isinstance(matches, list):
                        for m in matches:
                            if m.get("key") == match_key:
                                tba_match = m
                                break
                except Exception:
                    pass

            red_score, blue_score = 0, 0
            red_teams, blue_teams = [], []
            red_hub_total, blue_hub_total = 0, 0
            red_auto_pts, blue_auto_pts = 0, 0
            red_tower_pts, blue_tower_pts = 0, 0

            if tba_match:
                alliances = tba_match.get("alliances") or {}
                red_score = int((alliances.get("red") or {}).get("score") or 0)
                blue_score = int((alliances.get("blue") or {}).get("score") or 0)
                red_teams = (alliances.get("red") or {}).get("team_keys") or []
                blue_teams = (alliances.get("blue") or {}).get("team_keys") or []

                sb = tba_match.get("score_breakdown") or {}
                rsb = sb.get("red") or {}
                bsb = sb.get("blue") or {}
                red_hub_total = int((rsb.get("hubScore") or {}).get("totalCount") or 0)
                blue_hub_total = int((bsb.get("hubScore") or {}).get("totalCount") or 0)
                red_auto_pts = int(rsb.get("totalAutoPoints") or 0)
                blue_auto_pts = int(bsb.get("totalAutoPoints") or 0)
                red_tower_pts = int(rsb.get("totalTowerPoints") or 0)
                blue_tower_pts = int(bsb.get("totalTowerPoints") or 0)

            match_rows.append({
                "split": split,
                "year": int(year),
                "event_key": event_key,
                "match_key": match_key,
                "red_teams": ",".join(red_teams),
                "blue_teams": ",".join(blue_teams),
                "tba_red_score": red_score,
                "tba_blue_score": blue_score,
                "tba_combined_score": red_score + blue_score,
                "tba_total_hub_fuel_scored": red_hub_total + blue_hub_total,
                "tba_total_auto_points": red_auto_pts + blue_auto_pts,
                "tba_total_tower_points": red_tower_pts + blue_tower_pts,
                "vision_mean_red_bots": float(grp["red_robot_clusters"].mean()),
                "vision_mean_blue_bots": float(grp["blue_robot_clusters"].mean()),
                "vision_mean_total_bots": float(grp["total_robot_clusters"].mean()),
                "vision_mean_fuel_on_field": float(grp["raw_fuel_count"].mean()),
                "vision_max_fuel_on_field": int(grp["raw_fuel_count"].max()),
                "vision_total_defense_contacts": int(grp["defense_engagements"].sum()),
                "vision_total_incursions": int((grp["territory_incursion_red"] + grp["territory_incursion_blue"]).sum()),
                "vision_mean_conf": float(grp["mean_bumper_conf"].mean()),
                "venue_brightness": float(grp["brightness_mean"].mean()),
                "venue_glare_ratio": float(grp["glare_ratio"].mean()),
                "venue_sharpness": float(grp["sharpness_laplacian"].mean()),
            })

        df_matches = pd.DataFrame(match_rows)
        for target_dir in [self.repo_data_dir, self.ssd_data_dir]:
            df_matches.to_csv(target_dir / "match_level_tba_vision_summary.csv", index=False)
        return df_matches

    def generate_all_charts(
        self,
        df_frames: pd.DataFrame,
        df_boxes: pd.DataFrame,
        df_robots: pd.DataFrame,
        df_traj: pd.DataFrame,
        df_matches: pd.DataFrame,
    ) -> Dict[str, Any]:
        """Generates all 12 diagnostic charts and returns key summary statistics."""
        stats_summary: Dict[str, Any] = {}

        # Chart 1: Training Convergence & Validation Metrics
        self._chart_01_training_curves()

        # Chart 2: Zero-Label Rule-Invariant Accuracy Audit
        if not df_frames.empty:
            stats_summary.update(self._chart_02_rule_invariant_accuracy(df_frames, df_boxes))
            stats_summary.update(self._chart_03_cross_year_generalization(df_frames))
            self._chart_04_fuel_depletion_by_phase(df_frames)
            self._chart_05_field_spatial_heatmaps(df_boxes)
            self._chart_06_territory_and_defense(df_frames)
            self._chart_07_venue_lighting_ranking(df_frames)

        # Chart 8: TBA Score vs Vision Activity Correlation
        if not df_matches.empty:
            self._chart_08_tba_correlation(df_matches)

        # Charts 9-12: Per-Robot Telemetry, ML Role Clustering, Trajectories & OCR/Re-ID
        if not df_robots.empty:
            stats_summary.update(self._chart_09_per_robot_leaderboard(df_robots))
            stats_summary.update(self._chart_10_ml_role_clustering(df_robots))
            self._chart_12_robot_id_diagnostics(df_robots)
            self._generate_per_robot_scouting_catalog(df_robots, df_traj)

        if not df_traj.empty:
            self._chart_11_match_trajectories_board(df_traj)

        return stats_summary

